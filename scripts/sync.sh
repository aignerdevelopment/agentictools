#!/usr/bin/env bash
# Resolve the modules a project enables and materialise them for each agent.
# Only enabled modules are linked, so context stays small.
#
# Usage: [AGENTICTOOLS_HOME=/path] scripts/sync.sh [target-dir]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ -n "${AGENTICTOOLS_HOME:-}" ]; then
  :
elif [ -f "${1:-$PWD}/agentictools.config.json" ]; then
  AGENTICTOOLS_HOME="$(cd "$SCRIPT_DIR/.." && pwd)"
else
  AGENTICTOOLS_HOME="$(cd "$SCRIPT_DIR/.." && pwd)"
fi

TARGET="${1:-$PWD}"
CONFIG="$TARGET/agentictools.config.json"
REGISTRY="$AGENTICTOOLS_HOME/agentictools.json"
SERVERS="$AGENTICTOOLS_HOME/mcp/servers.json"

command -v jq >/dev/null 2>&1 || { echo "error: jq is required for sync.sh" >&2; exit 1; }
[ -f "$CONFIG" ] || { echo "error: $CONFIG not found; run bootstrap.sh first" >&2; exit 1; }
[ -f "$REGISTRY" ] || { echo "error: $REGISTRY not found" >&2; exit 1; }

# config.agentictoolsHome fills in the home when the env var is unset.
if [ -z "${AGENTICTOOLS_HOME:-}" ] || [ "$AGENTICTOOLS_HOME" = "$(cd "$SCRIPT_DIR/.." && pwd)" ]; then
  cfg_home="$(jq -r '.agentictoolsHome // empty' "$CONFIG")"
  [ -n "$cfg_home" ] && [ -d "$cfg_home" ] && AGENTICTOOLS_HOME="$cfg_home"
fi
[ -d "$AGENTICTOOLS_HOME" ] || { echo "error: invalid AGENTICTOOLS_HOME: $AGENTICTOOLS_HOME" >&2; exit 1; }

profile="$(jq -r '.profile // empty' "$CONFIG")"
maxrules="$(jq -r '.options.maxRules // 0' "$CONFIG")"
sync_dirs="$(jq -r '.options.syncGeneratedDirs // true' "$CONFIG")"
targets="$(jq -r '(.options.targets // ["claude","opencode","codex","antigravity"]) | join(" ")' "$CONFIG")"

mkdir -p "$TARGET/.agentictools"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

has_target() { case " $targets " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

enabled_ids() {
  local cat="$1" base inc exc all always
  base='[]'
  if [ -n "$profile" ]; then
    base="$(jq -c --arg p "$profile" --arg c "$cat" '(.profiles[$p][$c] // [])' "$REGISTRY")"
  fi
  inc="$(jq -c --arg c "$cat" '(.[$c] // {} | .include // [])' "$CONFIG")"
  exc="$(jq -c --arg c "$cat" '(.[$c] // {} | .exclude // [])' "$CONFIG")"
  all="$(jq -c --arg c "$cat" '((.modules[$c] // {}) | keys)' "$REGISTRY")"
  always='[]'
  if [ "$cat" = "rules" ]; then
    always="$(jq -c '[.modules.rules | to_entries[] | select((.value.tags // []) | index("always")) | .key]' "$REGISTRY")"
  fi
  jq -nr \
    --argjson base "$base" --argjson inc "$inc" --argjson exc "$exc" \
    --argjson all "$all" --argjson always "$always" '
    (if ($inc | index("*")) then $all else $inc end) as $i
    | ($base + $i + $always)
    | unique
    | map(select(. as $x | ($exc | index($x)) | not))
    | .[]'
}

for cat in rules skills prompts hooks agents workflows mcp tools; do
  enabled_ids "$cat" > "$tmp/$cat.ids"
  if [ "$cat" = "rules" ] && [ "$maxrules" -gt 0 ]; then
    head -n "$maxrules" "$tmp/$cat.ids" > "$tmp/$cat.ids.cap" && mv "$tmp/$cat.ids.cap" "$tmp/$cat.ids"
  fi
done

ids_json() { jq -R -s 'split("\n") | map(select(length > 0))' "$tmp/$1.ids"; }

# --- active.json -----------------------------------------------------------
jq -n \
  --arg home "$AGENTICTOOLS_HOME" \
  --arg profile "$profile" \
  --argjson rules "$(ids_json rules)" \
  --argjson skills "$(ids_json skills)" \
  --argjson prompts "$(ids_json prompts)" \
  --argjson hooks "$(ids_json hooks)" \
  --argjson agents "$(ids_json agents)" \
  --argjson workflows "$(ids_json workflows)" \
  --argjson mcp "$(ids_json mcp)" \
  --argjson tools "$(ids_json tools)" \
  '{home:$home, profile:(if $profile=="" then null else $profile end),
    rules:$rules, skills:$skills, prompts:$prompts, hooks:$hooks,
    agents:$agents, workflows:$workflows, mcp:$mcp, tools:$tools}' \
  > "$TARGET/.agentictools/active.json"

# --- active.md (the human/agent-facing index) ------------------------------
{
  echo "# agentictools - active modules"
  echo
  echo "Generated by scripts/sync.sh. Do not edit. Load only these."
  echo
  echo "- home: \`$AGENTICTOOLS_HOME\`"
  echo "- profile: \`${profile:-none}\`"
  echo
  for cat in rules skills prompts hooks agents workflows mcp tools; do
    ids="$(jq -R -s -r 'split("\n") | map(select(length > 0)) | .[]' "$tmp/$cat.ids")"
    [ -n "$ids" ] || continue
    echo "## $cat"
    echo
    while IFS= read -r id; do
      [ -n "$id" ] || continue
      path="$(jq -r --arg c "$cat" --arg i "$id" '.modules[$c][$i].path // ""' "$REGISTRY")"
      desc="$(jq -r --arg c "$cat" --arg i "$id" '.modules[$c][$i].description // ""' "$REGISTRY")"
      echo "- **$id**${desc:+ — $desc}"
      [ -n "$path" ] && echo "  - \`$AGENTICTOOLS_HOME/$path\`"
    done <<< "$ids"
    echo
  done
} > "$TARGET/.agentictools/active.md"

# --- symlinks --------------------------------------------------------------
link() {
  local src="$1" dest="$2"
  if [ ! -e "$src" ]; then echo "warn: missing source $src" >&2; return 0; fi
  mkdir -p "$(dirname "$dest")"
  if [ -e "$dest" ] && [ ! -L "$dest" ]; then
    echo "skip (exists, not a link): ${dest#"$TARGET"/}"
    return 0
  fi
  ln -sfn "$src" "$dest"
}

reset_link_dir() {
  local d="$TARGET/$1"
  [ -d "$d" ] || return 0
  find "$d" -maxdepth 1 -type l -delete 2>/dev/null || true
}

if [ "$sync_dirs" = "true" ]; then
  has_target claude && for d in .claude/skills .claude/agents .claude/commands; do reset_link_dir "$d"; done
  has_target opencode && for d in .opencode/skill .opencode/agent .opencode/command .opencode/plugin .opencode/tool; do reset_link_dir "$d"; done
  has_target codex && reset_link_dir .codex/prompts
  has_target antigravity && for d in .agents/skills .agents/workflows; do reset_link_dir "$d"; done
  reset_link_dir .agentictools/tools
fi

# skills
while IFS= read -r id; do
  [ -n "$id" ] || continue
  src="$AGENTICTOOLS_HOME/skills/$id"
  if has_target claude; then link "$src" "$TARGET/.claude/skills/$id"; fi
  if has_target opencode; then link "$src" "$TARGET/.opencode/skill/$id"; fi
  if has_target antigravity; then link "$src" "$TARGET/.agents/skills/$id"; fi
done < "$tmp/skills.ids"

# prompts + workflows -> per-target command/prompt/workflow files
for pair in "prompts.ids:prompts" "workflows.ids:workflows"; do
  idfile="${pair%%:*}"
  catdir="${pair##*:}"
  while IFS= read -r id; do
    [ -n "$id" ] || continue
    src="$AGENTICTOOLS_HOME/$catdir/$id.md"
    if has_target claude; then link "$src" "$TARGET/.claude/commands/$id.md"; fi
    if has_target opencode; then link "$src" "$TARGET/.opencode/command/$id.md"; fi
    if has_target codex; then link "$src" "$TARGET/.codex/prompts/$id.md"; fi
    if has_target antigravity; then link "$src" "$TARGET/.agents/workflows/$id.md"; fi
  done < "$tmp/$idfile"
done

# custom agents
while IFS= read -r id; do
  [ -n "$id" ] || continue
  if has_target claude && [ -f "$AGENTICTOOLS_HOME/agents/claude/$id.md" ]; then
    link "$AGENTICTOOLS_HOME/agents/claude/$id.md" "$TARGET/.claude/agents/$id.md"
  fi
  if has_target opencode && [ -f "$AGENTICTOOLS_HOME/agents/opencode/$id.md" ]; then
    link "$AGENTICTOOLS_HOME/agents/opencode/$id.md" "$TARGET/.opencode/agent/$id.md"
  fi
done < "$tmp/agents.ids"

# tools: file tools are linked as-is; directory tools become a local dir of
# symlinks (central edits propagate, while config.json / .venv stay local).
while IFS= read -r id; do
  [ -n "$id" ] || continue
  tpath="$(jq -r --arg i "$id" '.modules.tools[$i].path // ""' "$REGISTRY")"
  [ -n "$tpath" ] || continue
  src="$AGENTICTOOLS_HOME/$tpath"
  if [ -d "$src" ]; then
    dest="$TARGET/.agentictools/tools/$id"
    mkdir -p "$dest"
    find "$dest" -maxdepth 1 -type l -delete 2>/dev/null || true
    for entry in "$src"/*; do
      [ -e "$entry" ] || continue
      ln -sfn "$entry" "$dest/$(basename "$entry")"
    done
  else
    base="$(basename "$tpath")"
    link "$src" "$TARGET/.agentictools/tools/$base"
    case "$base" in
      *.ts) if has_target opencode; then link "$src" "$TARGET/.opencode/tool/$base"; fi ;;
    esac
  fi
done < "$tmp/tools.ids"

# --- hooks -----------------------------------------------------------------
# settings.local.json is fully generated (gitignored), so start clean each run.
if has_target claude; then
  mkdir -p "$TARGET/.claude"
  echo '{}' > "$TARGET/.claude/settings.local.json"
fi
if [ -s "$tmp/hooks.ids" ]; then
  if has_target claude; then
    base="$TARGET/.claude/settings.local.json"
    sed "s#{{AGENTICTOOLS_HOME}}#$AGENTICTOOLS_HOME#g" \
      "$AGENTICTOOLS_HOME/hooks/claude/settings.hooks.json" > "$tmp/claude-hooks.json"
    jq -s '.[0] * .[1]' "$base" "$tmp/claude-hooks.json" > "$base.tmp" \
      && mv "$base.tmp" "$base"
  fi
  if has_target opencode; then
    for f in "$AGENTICTOOLS_HOME"/hooks/opencode/*.ts; do
      [ -e "$f" ] || continue
      link "$f" "$TARGET/.opencode/plugin/$(basename "$f")"
    done
  fi
fi

# --- MCP -------------------------------------------------------------------
collect_servers() {
  local target="$1" out='{}'
  while IFS= read -r id; do
    [ -n "$id" ] || continue
    frag="$(jq -c --arg id "$id" --arg t "$target" '.servers[$id].config[$t] // empty' "$SERVERS")"
    [ -n "$frag" ] || continue
    out="$(jq -nc --argjson a "$out" --arg id "$id" --argjson b "$frag" '$a + {($id): $b}')"
  done < "$tmp/mcp.ids"
  printf '%s' "$out"
}

if [ -f "$SERVERS" ]; then
  if has_target claude; then
    collect_servers claude | jq '{mcpServers: .}' > "$TARGET/.mcp.json"
  fi
  if has_target antigravity; then
    mkdir -p "$TARGET/.agents"
    collect_servers antigravity | jq '{mcpServers: .}' > "$TARGET/.agents/mcp_config.json"
  fi
  if has_target codex; then
    mkdir -p "$TARGET/.agentictools" "$TARGET/.codex"
    {
      echo "# >>> agentictools managed (do not edit) >>>"
      while IFS= read -r id; do
        [ -n "$id" ] || continue
        cfg="$(jq -c --arg id "$id" '.servers[$id].config.codex // empty' "$SERVERS")"
        [ -n "$cfg" ] || continue
        echo "[mcp_servers.$id]"
        url="$(jq -r '.url // empty' <<<"$cfg")"
        cmd="$(jq -r '.command // empty' <<<"$cfg")"
        [ -n "$url" ] && echo "url = \"$url\""
        [ -n "$cmd" ] && echo "command = \"$cmd\""
        args="$(jq -r '(.args // []) | map("\"" + . + "\"") | join(", ")' <<<"$cfg")"
        [ -n "$args" ] && echo "args = [$args]"
        jq -r '(.env // {}) | to_entries[] | .key + " = \"" + .value + "\""' <<<"$cfg" || true
        echo
      done < "$tmp/mcp.ids"
      echo "# <<< agentictools managed <<<"
    } > "$TARGET/.agentictools/codex-mcp.toml"
    if [ -f "$TARGET/.codex/config.toml" ]; then
      sed -e '/# >>> agentictools managed/,/# <<< agentictools managed/d' \
        "$TARGET/.codex/config.toml" > "$TARGET/.codex/config.toml.tmp"
      cat "$TARGET/.agentictools/codex-mcp.toml" >> "$TARGET/.codex/config.toml.tmp"
      mv "$TARGET/.codex/config.toml.tmp" "$TARGET/.codex/config.toml"
    fi
  fi
fi

# opencode reads a single project config; generate it with the redirect
# instructions plus the enabled MCP servers.
if has_target opencode; then
  mkdir -p "$TARGET/.opencode"
  servers_json='{}'
  [ -f "$SERVERS" ] && servers_json="$(collect_servers opencode)"
  jq -n --arg home "$AGENTICTOOLS_HOME" --argjson mcp "$servers_json" '{
    "$schema": "https://opencode.ai/config.json",
    instructions: ["AGENTS.md", ($home + "/AGENTS.md"), ".agentictools/active.md"],
    mcp: $mcp
  }' > "$TARGET/.opencode/opencode.json"
fi

echo "synced agentictools -> $TARGET"
echo "  profile : ${profile:-none}"
echo "  targets : $targets"
echo "  active  : .agentictools/active.md"
